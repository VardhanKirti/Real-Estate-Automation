/** +3 / -2 / 0 for count deltas (true minus sign). */
export function fmtDeltaCount(d: number): string {
  if (!Number.isFinite(d)) return '';
  const r = Math.round(d);
  if (r === 0) return '0';
  return r > 0 ? `+${r}` : `${MINUS}${Math.abs(r)}`;
}

/** 12 Oct (or 12 Oct 2026) in process local time or the given time zone. */
export function fmtLabDay(iso: string, opts: { year?: boolean; tz?: string } = {}): string {
  const d = new Date(iso);
  if (Number.isNaN(d.getTime())) return '';
  return new Intl.DateTimeFormat('en-GB', { day: 'numeric', month: 'short', year: opts.year ? 'numeric' : undefined, timeZone: opts.tz }).format(d);
}

/** Elapsed time for live progress: 48s, 1m 12s, 1h 04m (09.8 "Running, {elapsed}"). */
export function fmtElapsed(seconds: number): string {
  const s = Math.max(0, Math.floor(Number.isFinite(seconds) ? seconds : 0));
  if (s < 60) return `${s}s`;
  const m = Math.floor(s / 60);
  if (m < 60) return `${m}m ${String(s % 60).padStart(2, '0')}s`;
  return `${Math.floor(m / 60)}h ${String(m % 60).padStart(2, '0')}m`;
}

